"""Fills the programme's synopsis template in place from reports/report_data.json (numbers come from saved results).
Placeholders owned by the learner (name, roll no., college, mentor, date), the declaration tick-boxes and the signature are NOT touched."""
import json
import docx
from docx.shared import Pt, RGBColor, Inches
from docx.enum.text import WD_ALIGN_PARAGRAPH

TEMPLATE = '/mnt/user-data/uploads/Project_Synopsis_Template_1.docx'
OUT = 'reports/Project_Synopsis_YourName_RollNo.docx'
D = json.load(open('reports/report_data.json')); f = D['facts']; F = D['figs']
d = docx.Document(TEMPLATE)
P = list(d.paragraphs)


def reset(p):
    for r in list(p.runs):
        r._r.getparent().remove(r._r)


def write(p, lines):
    """lines: list of str or (label, text); labels are bold. Plain black Arial 10 pt (replaces the orange guidance text)."""
    reset(p)
    for i, ln in enumerate(lines):
        if i: p.add_run().add_break()
        parts = ln if isinstance(ln, tuple) else (None, ln)
        for k, (txt, bold) in enumerate([(parts[0], True), (parts[1], False)] if parts[0] else [(parts[1], False)]):
            r = p.add_run(txt if k == 0 or not parts[0] else ' ' + txt)
            r.font.name, r.font.size, r.font.bold, r.font.italic = 'Arial', Pt(10), bold, False
            r.font.color.rgb = RGBColor(0, 0, 0)


heads = {p.text: p for p in P}
# 1. problem statement (5W1H)
write(P[5], [f'Streaming viewers face catalogues too large to browse, and popularity lists bury regional-language films, which lowers engagement and traps viewers in a filter bubble. '
             f'This project builds collaborative-filtering recommenders (user-based, item-based and SVD), evaluates them with RMSE and precision@K, and audits them for diversity and fairness so that suggestions are both relevant and varied.'])
# 2. solution
write(P[7], [f'I built a Python recommender with user-based and item-based collaborative filtering and SVD matrix factorisation (Surprise), compared against mean, bias and popularity baselines on a leakage-free, per-user chronological split. '
             f'The deployed model (item-based CF blended with popularity) is served through a Flask REST API (recommend, similar, history, explain) and a Streamlit dashboard, with a popularity fallback for new users. '
             f'A diversity re-ranker (MMR with an exposure penalty) counters filter bubbles, and every result states that the data is synthetic. '
             f'Everything is reproducible from fixed seeds and covered by {f["n_tests"]} automated tests.'])
# 3. architecture: DFD level 0 + block diagram
p = P[9]; reset(p); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
p.add_run().add_picture(F['arch_dfd_level0']['path'], width=Inches(5.0))
nxt = P[10]


def after(par_before, kind, arg):
    np_ = nxt.insert_paragraph_before(); np_.alignment = WD_ALIGN_PARAGRAPH.CENTER
    if kind == 'caption':
        r = np_.add_run(arg); r.font.name, r.font.size, r.font.italic = 'Arial', Pt(8.5), True; r.font.color.rgb = RGBColor(0x6B, 0x72, 0x80)
    else:
        np_.add_run().add_picture(arg, width=Inches(6.3))
    return np_
after(p, 'caption', 'Figure 1: Level-0 data flow diagram')
after(p, 'image', F['arch_block_diagram']['path'])
after(p, 'caption', 'Figure 2: System block diagram (data pipeline, models, evaluation and delivery)')
# 4. technology stack
write(P[11], [('Frontend / UI:', 'Streamlit dashboard (plus a JSON REST API for other clients)'), ('Backend / Logic:', f'Python {f["py"]}, Flask REST API, shared service layer (src/serving.py)'),
              ('Database:', 'None: data is stored as CSV files; no database server or SQL was needed'), ('AI/ML Framework:', 'Surprise (SVD); own NumPy implementations of item-based and user-based CF; pandas, SciPy'),
              ('Visualisation:', 'matplotlib and seaborn (EDA notebook), Streamlit charts'), ('Hardware:', f'Standard laptop CPU, no GPU needed (median API response {f["lat_med"]} ms)')])
# 5. dataset
write(P[13], [('Dataset file name:', 'dataset.csv (provided in project folder; cleaned version delivered)'), ('Number of rows:', f'{f["rows"]:,} ({f["orig"]} from the provided file + {f["gen"]:,} synthetic)'),
              ('Number of columns:', f'{f["cols"]} (the 7 provided columns + movie_id + is_original)'), ('Key columns (list 5):', 'user_id, movie_id, rating, timestamp, genre (also language, release_year)'),
              ('Any additional data collected:', f'Yes: {f["gen"]:,} synthetic ratings and a {f["catalogue"]}-film catalogue, generated by a seeded script (src/generate_data.py) because the provided file had only {f["raw_titles"]} movies and about 1.6 ratings per user. '
               'Assumptions are documented in docs/data_source.md; no real MovieLens rows were used.')])
# 6. metrics
write(P[15], [('Metric 1: Test RMSE (item-based CF)', f'{f["rmse_item_cf"]} vs {f["rmse_item_mean"]} for the item-mean baseline (difference {f["d_itemmean"]}); no gain over a user-bias + movie-bias baseline ({f["rmse_bias"]}).'),
              ('Metric 2: Precision@10 and coverage', f'P@10 {f["p10_dep"]} for the deployed CF + popularity blend vs {f["p10_pop"]} for plain popularity (a tie). Catalogue coverage@10 rises from {f["cov_dep"]} to {f["cov_safe"]} with the diversity re-ranker (P@10 {f["p10_safe"]}, {f["loss_safe"]} lower).'),
              ('Metric 3: API response time', f'median {f["lat_med"]} ms, 95th percentile {f["lat_p95"]} ms ({f["lat_n"]} real HTTP requests); {f["n_tests"]} automated tests pass.'),
              ('Business value achieved:', 'A working, tested recommender with a diversity control and an honest evaluation. It shows where collaborative filtering helps (beats item averages), where it does not (no gain over simple biases on sparse data) and how to reduce the filter-bubble effect. Results come from synthetic data and are not findings about real viewers.')])
# 7. challenges
write(P[17], [('Challenge 1:', f'the provided dataset had only {f["raw_titles"]} movies, about 1.6 ratings per user and random genre/language per row, so collaborative filtering was impossible. '
               '→ Resolution: built a consistent 126-film catalogue and a documented, seeded synthetic extension to 5,000 ratings, kept the original rows flagged (is_original), and stated in every deliverable that results concern synthetic data.'),
              ('Challenge 2:', 'collaborative filtering barely beat simple baselines, popularity beat pure CF, and a blend that looked better on validation only tied popularity on the test set. '
               f'→ Resolution: added a bias baseline, tuned on rolling time-respecting folds, used bootstrap confidence intervals, opened the test set once and reported the result honestly; added a diversity re-ranker (coverage {f["cov_dep"]} → {f["cov_safe"]}) against filter bubbles.')])
# 8. references
write(P[19], [('1.', 'Harper, F. M. and Konstan, J. A. (2015). The MovieLens Datasets: History and Context. ACM Transactions on Interactive Intelligent Systems, 5(4), Article 19. https://grouplens.org/datasets/movielens/'),
              ('2.', 'Koren, Y., Bell, R. and Volinsky, C. (2009). Matrix Factorization Techniques for Recommender Systems. Computer, 42(8), 30-37.'),
              ('3.', 'Hug, N. (2020). Surprise: A Python library for recommender systems. Journal of Open Source Software, 5(52), 2174.'),
              ('4.', 'Sarwar, B., Karypis, G., Konstan, J. and Riedl, J. (2001). Item-based collaborative filtering recommendation algorithms. Proceedings of the 10th International Conference on World Wide Web, 285-295.'),
              ('5.', 'Carbonell, J. and Goldstein, J. (1998). The use of MMR, diversity-based reranking for reordering documents and producing summaries. Proceedings of SIGIR 1998, 335-336.'),
              ('6.', 'HCLTech Career Shaper Programme: Project Brief (Project 28), Dataset Generation Prompt and Programme Guidelines (provided by the Programme Coordinator).')])
# 9. declaration: untouched; add a note that it is the learner's to tick and sign
note = P[22].insert_paragraph_before() if False else P[23].insert_paragraph_before()
r = note.add_run("[To be read, ticked and signed by the learner. Not completed by the AI assistant. AI-tool use is disclosed in Appendix A of the project report.]")
r.font.name, r.font.size, r.font.italic = 'Arial', Pt(9), True; r.font.color.rgb = RGBColor(0xC0, 0x55, 0x00)
from docx.oxml.ns import qn
z = d.settings.element.find(qn('w:zoom'))
if z is not None and z.get(qn('w:percent')) is None:        # the template's zoom element lacks the required percent attribute
    z.set(qn('w:percent'), '100')
d.core_properties.title = 'Project Synopsis - Personalized Movie Recommendation System Using Collaborative Filtering'
d.save(OUT); print('saved', OUT)
