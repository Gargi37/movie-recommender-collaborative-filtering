"""Stage 9 diagnostics (train data only; test.csv never read):
 A) learning curve: does CF gain over the bias baseline when it sees more ratings per user?
 B) popularity blend: accuracy vs catalogue-coverage trade-off, alpha chosen on the two rolling folds."""
import json
import numpy as np, pandas as pd
from src.data import per_user_split
from src.baselines import BiasBaseline, PopularityRec
from src.item_cf import ItemCF
from src.svd import SVDMF
from src.hybrid import BlendRec
from src.metrics import rating_eval, ranking_eval

read = lambda n: pd.read_csv(f'data/processed/split/{n}.csv', parse_dates=['timestamp'])
train_core, val = read('train_core'), read('val')
a, b = per_user_split(train_core, 0.25)
FOLDS = [(a, b), (train_core, val)]
P = json.load(open('results/best_params.json')); lam = P['lam']
mk = {'bias': lambda: BiasBaseline(**lam), 'item_cf': lambda: ItemCF(**P['item_cf'], **lam), 'svd': lambda: SVDMF(**P['svd'])}
L = ['# Stage 9 diagnostics (auto-generated by src/diagnostics.py; train data only)', '']

L += ['## A) Learning curve (fit on the earliest X% of each user\'s train_core ratings, score on validation)', '',
      '| Share of train_core used | Ratings | Bias baseline RMSE | Item CF RMSE | SVD RMSE | Item CF - Bias | SVD - Bias |', '|---|---|---|---|---|---|---|']
for frac in [0.25, 0.5, 0.75, 1.0]:
    sub = train_core if frac == 1 else per_user_split(train_core, 1 - frac)[0]
    r = {k: rating_eval(f().fit(sub), val)['rmse'] for k, f in mk.items()}
    L.append(f"| {frac:.0%} | {len(sub)} | {r['bias']:.4f} | {r['item_cf']:.4f} | {r['svd']:.4f} | {r['item_cf'] - r['bias']:+.4f} | {r['svd'] - r['bias']:+.4f} |")
L += ['', '(Negative = better than the baseline. Differences below about 0.01 are within noise for ~800 validation ratings.)', '']

L += ['## B) Popularity blend (ranking), mean of the two rolling folds', '',
      '| Model | alpha | P@10 | R@10 | Coverage@10 |', '|---|---|---|---|---|']
def fold_mean(make):
    o = [ranking_eval(make().fit(tr), tr, te, 10) for tr, te in FOLDS]
    return {k: float(np.mean([x[k] for x in o])) for k in ('precision', 'recall', 'coverage')}
pop = fold_mean(PopularityRec); L.append(f"| Popularity only | inf | {pop['precision']:.4f} | {pop['recall']:.4f} | {pop['coverage']:.3f} |")
best_blend = {}
for name in ['item_cf', 'svd']:
    rows = []
    for al in [0, 0.25, 0.5, 1, 2, 4, 8]:
        m = fold_mean(lambda: BlendRec(mk[name](), alpha=al)); rows.append((al, m))
        L.append(f"| {name} + popularity | {al} | {m['precision']:.4f} | {m['recall']:.4f} | {m['coverage']:.3f} |")
    best_blend[name] = max(rows, key=lambda x: x[1]['precision'])[0]
L += ['', f'Alpha with the highest mean-fold P@10: {best_blend}. Higher alpha means more popularity, so lower coverage and less diversity (see Stage 10 audit).']
json.dump(best_blend, open('results/best_blend_alpha.json', 'w'))
open('docs/stage9_diagnostics.md', 'w').write('\n'.join(L)); print('\n'.join(L))
