"""Experiment table: results/experiments.csv (+ docs/experiments.md). Rows are replaced by exp_id, so reruns are idempotent."""
from pathlib import Path
import pandas as pd

COLS = ['exp_id', 'stage', 'model', 'settings', 'fit_on', 'eval_on', 'RMSE', 'MAE', 'P@10', 'R@10', 'Hit@10', 'Coverage@10', 'users_scored', 'notes']
CSV = Path('results/experiments.csv')


def log(rows):
    CSV.parent.mkdir(exist_ok=True)
    new = pd.DataFrame(rows, columns=COLS)
    old = pd.read_csv(CSV) if CSV.exists() else pd.DataFrame(columns=COLS)
    df = pd.concat([old[~old.exp_id.isin(new.exp_id)], new]).sort_values('exp_id').reset_index(drop=True)
    df.to_csv(CSV, index=False)
    fmt = df.copy()
    for c in ['RMSE', 'MAE', 'P@10', 'R@10', 'Hit@10', 'Coverage@10']:
        fmt[c] = fmt[c].map(lambda v: '' if pd.isna(v) else f'{v:.3f}')
    fmt['users_scored'] = fmt.users_scored.map(lambda v: '' if pd.isna(v) else str(int(v)))
    fmt = fmt.fillna('')
    lines = ['# Experiment table (auto-generated by src/experiments.py)', '',
             '| ' + ' | '.join(COLS) + ' |', '|' + '---|' * len(COLS)] + ['| ' + ' | '.join(map(str, r)) + ' |' for r in fmt.values]
    Path('docs/experiments.md').write_text('\n'.join(lines))
    return df
