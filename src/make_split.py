"""Stage 7 - create splits, check leakage/cold-start, write data/processed/split/*.csv and docs/split_report.md"""
import hashlib
from pathlib import Path
import numpy as np
import pandas as pd
from src.data import load_clean, make_splits, per_user_split, build_index, to_csr, MODEL_COLS, TEST_FRAC, VAL_FRAC, RELEVANT

SEED = 42
df = load_clean()
train_core, val, train_full, test = make_splits(df)
out = Path('data/processed/split'); out.mkdir(parents=True, exist_ok=True)
for name, d in [('train_core', train_core), ('val', val), ('train_full', train_full), ('test', test)]:
    x = d.copy(); x['timestamp'] = x.timestamp.dt.strftime('%Y-%m-%d %H:%M:%S'); x.to_csv(out / f'{name}.csv', index=False)
sha = hashlib.sha256((out / 'test.csv').read_bytes()).hexdigest()

# ---- integrity checks (also asserted in tests/test_split.py)
def key(d): return set(zip(d.user_id, d.movie_id))
assert len(train_full) + len(test) == len(df) and not key(train_full) & key(test)
assert len(train_core) + len(val) == len(train_full) and not key(train_core) & key(val)
g1 = train_full.groupby('user_id').timestamp.max(); g2 = test.groupby('user_id').timestamp.min()
assert (g1.reindex(g2.index) <= g2).all(), 'a user has a training rating later than a test rating'
g3 = train_core.groupby('user_id').timestamp.max(); g4 = val.groupby('user_id').timestamp.min()
assert (g3.reindex(g4.index) <= g4).all()

# ---- cold start
u2i, i2i = build_index(train_full)
cold_users = (~test.user_id.isin(u2i)).sum()
cold_item_rows = (~test.movie_id.isin(i2i)); cold_items = test.loc[cold_item_rows, 'movie_id'].nunique()
u2c, i2c = build_index(train_core)
val_cold_rows = (~val.movie_id.isin(i2c)).sum(); val_cold_users = (~val.user_id.isin(u2c)).sum()
Rtr = to_csr(train_full, u2i, i2i)
thin = (np.diff(Rtr.tocsc().indptr) < 5).sum()
tpu = test.groupby('user_id').size()

# ---- illustration on TRAIN_FULL only (test labels untouched): random vs chronological hold-out
def bias_rmse(tr, te, lam_i=5, lam_u=10):
    mu = tr.rating.mean(); r = tr.rating - mu
    bi = (r.groupby(tr.movie_id).sum() / (r.groupby(tr.movie_id).size() + lam_i))
    r2 = r - tr.movie_id.map(bi)
    bu = (r2.groupby(tr.user_id).sum() / (r2.groupby(tr.user_id).size() + lam_u))
    p = mu + te.movie_id.map(bi).fillna(0) + te.user_id.map(bu).fillna(0)
    return np.sqrt(((te.rating - p.clip(1, 5)) ** 2).mean())
def gm_rmse(tr, te): return np.sqrt(((te.rating - tr.rating.mean()) ** 2).mean())
c_tr, c_te = per_user_split(train_full, 0.2)
rng = np.random.default_rng(SEED); m = rng.random(len(train_full)) < 0.2
r_tr, r_te = train_full[~m], train_full[m]
def cold(tr, te): return (~te.movie_id.isin(set(tr.movie_id))).mean()

# ---- how much does the test hold
orig_share_all, orig_share_test = df.is_original.mean(), test.is_original.mean()
