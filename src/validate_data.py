"""Stage 3 - independent validation of data/raw/dataset_extended.csv. Writes docs/data_validation_report.md"""
import re
import numpy as np
import pandas as pd
from pathlib import Path

RAW = Path('data/raw')
df = pd.read_csv(RAW / 'dataset_extended.csv')
orig_raw = pd.read_csv(RAW / 'dataset.csv')
cat = pd.read_csv(RAW / 'movie_catalogue.csv')
checks = []
def check(name, ok, detail=''):
    checks.append((name, bool(ok), detail))

check('Same first 7 column names/order as provided dataset.csv', list(df.columns[:7]) == list(orig_raw.columns), str(list(df.columns)))
check('Row count = 5000', len(df) == 5000, str(len(df)))
check('No missing values', df.isna().sum().sum() == 0)
check('No duplicate (user, movie) pairs', not df.duplicated(['user_id', 'movie_id']).any())
check('Ratings are 1.0-5.0 in 0.5 steps', df.rating.between(1, 5).all() and ((df.rating * 2) % 1 == 0).all())
pu = df.groupby('user_id').size(); pi = df.groupby('movie_id').size()
check('Every user has 15-25 ratings', pu.between(15, 25).all(), f'min {pu.min()} max {pu.max()}')
check('One genre/language/year per title', (df.groupby('movie_title')[['genre', 'language', 'release_year']].nunique() == 1).all().all())
merged = df.merge(cat, on='movie_id', suffixes=('', '_c'))
check('Attributes match catalogue', (merged.genre == merged.genre_c).all() and (merged.language == merged.language_c).all() and (merged.release_year == merged.release_year_c).all())
check('Timestamp format YYYY-MM-DD HH:MM:SS', df.timestamp.map(lambda s: bool(re.fullmatch(r'\d{4}-\d\d-\d\d \d\d:\d\d:\d\d', s))).all())
ts = pd.to_datetime(df.timestamp)
check('Timestamps sequential (sorted ascending)', ts.is_monotonic_increasing)
check('Timestamps within 2024-01-01..2025-12-31', ts.min() >= pd.Timestamp('2024-01-01') and ts.max() < pd.Timestamp('2026-01-01'), f'{ts.min()} .. {ts.max()}')
check('No rating before release year', (ts.dt.year >= df.release_year).all())
o = df[df.is_original]
o_raw = orig_raw.sort_values('timestamp').drop_duplicates(['user_id', 'movie_title'], keep='last')
chk = o.merge(o_raw, on=['user_id', 'movie_title'], suffixes=('', '_r'))
check('Original rows kept with identical ratings (473)', len(o) == len(o_raw) == len(chk) and (chk.rating == chk.rating_r).all(), f'{len(o)} kept')
check('Original date preserved', (chk.timestamp.str[:10] == chk.timestamp_r).all())
check('No demographic/PII columns', set(df.columns) <= {'user_id','movie_title','genre','language','release_year','rating','timestamp','movie_id','is_original'})

# signal sanity check (NOT a reported result: random split, only proves collaborative signal exists)
from surprise import Dataset, Reader, SVD, accuracy
from surprise.model_selection import train_test_split
d = Dataset.load_from_df(df[['user_id', 'movie_id', 'rating']], Reader(rating_scale=(1, 5)))
tr, te = train_test_split(d, test_size=.2, random_state=42)
gm = tr.global_mean
im = {tr.to_raw_iid(i): np.mean([r for _, r in tr.ir[i]]) for i in tr.ir}
y = np.array([r for _, _, r in te]); items = [i for _, i, _ in te]
rm_g = np.sqrt(np.mean((y - gm) ** 2))
rm_i = np.sqrt(np.mean((y - np.array([im.get(i, gm) for i in items])) ** 2))
svd = SVD(n_factors=20, random_state=42).fit(tr)
rm_s = accuracy.rmse(svd.test(te), verbose=False)

density = len(df) / (df.user_id.nunique() * df.movie_id.nunique())
lines = ['# Data Validation Report (auto-generated by src/validate_data.py)', '', '## Checks', '| Check | Result | Detail |', '|---|---|---|']
lines += [f'| {n} | {"PASS" if ok else "FAIL"} | {d} |' for n, ok, d in checks]
lines += ['', '## Size and sparsity',
  f'- Rows {len(df)}, users {df.user_id.nunique()}, movies rated {df.movie_id.nunique()} (catalogue {len(cat)}), density {density:.1%}',
  f'- Ratings per user: min {pu.min()}, median {pu.median():.0f}, mean {pu.mean():.1f}, max {pu.max()}',
  f'- Ratings per movie: min {pi.min()}, median {pi.median():.0f}, mean {pi.mean():.1f}, max {pi.max()}; movies with < 5 ratings: {(pi < 5).sum()}',
  f'- Rows from provided file: {int(df.is_original.sum())}; generated: {int((~df.is_original).sum())}',
  '', '## Rating distribution', f'- mean {df.rating.mean():.2f}, std {df.rating.std():.2f}', '- counts: ' + str(df.rating.value_counts().sort_index().to_dict()),
  '', '## Catalogue share vs rating share (%)', '| Language | Catalogue | Ratings |', '|---|---|---|']
cs = cat.language.value_counts(normalize=True) * 100; rs = df.language.value_counts(normalize=True) * 100
lines += [f'| {l} | {cs[l]:.1f} | {rs[l]:.1f} |' for l in cs.index]
lines += ['', '| Genre | Catalogue | Ratings |', '|---|---|---|']
cg = cat.genre.value_counts(normalize=True) * 100; rg = df.genre.value_counts(normalize=True) * 100
lines += [f'| {g} | {cg[g]:.1f} | {rg[g]:.1f} |' for g in cg.index]
lines += ['', '## Signal sanity check (random 80/20 split; NOT a Stage-10 result)',
  f'- Global-mean RMSE {rm_g:.3f} | item-mean RMSE {rm_i:.3f} | SVD(20 factors, defaults) RMSE {rm_s:.3f}',
  '- Purpose: confirm the synthetic data contains learnable collaborative signal. Final evaluation uses a chronological split.']
Path('docs/data_validation_report.md').write_text('\n'.join(lines))
print('\n'.join(lines))
print('\nALL CHECKS PASSED' if all(ok for _, ok, _ in checks) else '\nSOME CHECKS FAILED')
