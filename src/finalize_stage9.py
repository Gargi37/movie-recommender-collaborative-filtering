"""Stage 9 finalisation (test.csv is never read):
 1. log tuned models in the experiment table (fit train_core -> score validation)
 2. SVD seed-robustness check
 3. refit the selected configurations on train_full and save them with joblib
 4. write docs/model_selection.md"""
import json
from pathlib import Path
import joblib
import numpy as np
import pandas as pd
from src.baselines import BiasBaseline, PopularityRec
from src.item_cf import ItemCF
from src.user_cf import UserCF
from src.svd import SVDMF
from src.hybrid import BlendRec
from src.metrics import rating_eval, ranking_eval
from src.experiments import log
from src.recommender import Recommender

read = lambda n: pd.read_csv(f'data/processed/split/{n}.csv', parse_dates=['timestamp'])
train_core, val, train_full = read('train_core'), read('val'), read('train_full')
cat = pd.read_csv('data/raw/movie_catalogue.csv')
P = json.load(open('results/best_params.json')); lam = P['lam']; ALPHA = json.load(open('results/best_blend_alpha.json'))
builders = {
    'E10': ('Bias baseline (tuned)', lambda: BiasBaseline(**lam), lam),
    'E11': ('Item-based CF (tuned)', lambda: ItemCF(**P['item_cf'], **lam), P['item_cf']),
    'E12': ('User-based CF (tuned)', lambda: UserCF(**P['user_cf'], **lam), P['user_cf']),
    'E13': ('SVD / matrix factorisation (tuned)', lambda: SVDMF(**P['svd']), P['svd']),
    'E14': ('Item CF + popularity blend', lambda: BlendRec(ItemCF(**P['item_cf'], **lam), alpha=ALPHA['item_cf']), {**P['item_cf'], 'alpha': ALPHA['item_cf']}),
    'E15': ('SVD + popularity blend', lambda: BlendRec(SVDMF(**P['svd']), alpha=ALPHA['svd']), {**P['svd'], 'alpha': ALPHA['svd']}),
}
# 2. SVD seed robustness (validation RMSE over 5 seeds)
seeds = [rating_eval(SVDMF(**{**P['svd'], 'seed': s}).fit(train_core), val)['rmse'] for s in range(5)]
rows = []
for eid, (name, make, cfg) in builders.items():
    m = make().fit(train_core)
    r = rating_eval(m, val); k = ranking_eval(m, train_core, val, 10)
    note = 'Tuned on 2 rolling folds of train data; fold 2 = this validation set, so slightly optimistic'
    if eid == 'E13':
        note += f'; SVD RMSE over 5 seeds {np.mean(seeds):.4f} +/- {np.std(seeds):.4f}'
    if eid in ('E14', 'E15'):
        note = 'Ranking blend; rating predictions = base model. alpha chosen on folds by P@10'
    rows.append([eid, 9, name, ', '.join(f'{a}={b}' for a, b in cfg.items()), 'train_core', 'val', r['rmse'], r['mae'], k['precision'], k['recall'], k['hit_rate'], k['coverage'], k['users'], note])
df = log(rows)

# 3. refit on train_full and persist
Path('models').mkdir(exist_ok=True)
final = {}
for key, (name, make, cfg) in {'bias': builders['E10'], 'item_cf': builders['E11'], 'user_cf': builders['E12'], 'svd': builders['E13'], 'item_cf_blend': builders['E14'], 'svd_blend': builders['E15']}.items():
    m = make().fit(train_full); m.meta = cat
    joblib.dump(m, f'models/{key}.joblib'); final[key] = m
pop = PopularityRec().fit(train_full); pop.meta = cat
joblib.dump(pop, 'models/popularity.joblib')
Recommender(final['item_cf_blend'], pop, cat, train_full).save('models/final_recommender.joblib')

# 4. documentation
g = {k: pd.read_csv(f'results/grid_{k}.csv') for k in ['bias', 'item_cf', 'user_cf', 'svd']}
best_rmse = {k: v.rmse.iloc[0] for k, v in g.items()}
L = ['# Model selection (Stage 9, auto-generated by src/finalize_stage9.py)', '',
 '## Protocol', '- Tuning used only train data: two rolling time-respecting folds (fold 1: first 75% of each user\'s train_core -> next 25%; fold 2: train_core -> validation).',
 '- Selection rule, declared before the grids ran: lowest mean RMSE over the two folds. Ranking blend alpha: highest mean-fold P@10.',
 '- The test set was not loaded by any Stage 9 script. Selected configurations were refit on train_full (models/*.joblib).',
 '- Bias baseline damping was tuned first; CF models reuse those values (lam_i, lam_u) so the comparison is fair.',
 '', '## Grids and winners (mean-fold RMSE)', '| Model | Configs tried | Best config | Mean-fold RMSE |', '|---|---|---|---|']
L += [f"| {n} | {len(g[k])} | {P[k]} | {best_rmse[k]:.4f} |" for n, k in [('Bias baseline', 'bias'), ('Item-based CF', 'item_cf'), ('User-based CF', 'user_cf'), ('SVD', 'svd')]]
L += ['', '## Reading the result honestly',
 f"- All CF models are within {max(best_rmse.values()) - min(best_rmse.values()):.4f} RMSE of each other and of the tuned bias baseline ({best_rmse['bias']:.4f}). With ~900 scored ratings per fold these gaps are below noise.",
 '- Item CF\'s best settings drift towards heavy shrinkage and light damping, i.e. towards the baseline: personalisation adds little to rating accuracy on this sparse data. SVD has an interior optimum and beat the baseline at every learning-curve point but only by 0.003-0.010 (docs/stage9_diagnostics.md).',
 f"- By the declared rule the nominal winner is item-based CF ({best_rmse['item_cf']:.4f}); the margin over SVD ({best_rmse['svd']:.4f}) is not meaningful. Stage 10 evaluates ALL tuned models on the test set once, and the deployed model stays the pre-declared one.",
 '- For ranking, popularity beats pure CF. A CF + popularity blend (alpha chosen on folds) beats both on P@10, at the cost of low catalogue coverage; the Stage 10 diversity audit must address this.',
 '- Grids were widened once to avoid edge-of-grid winners. Item CF still ends at an edge (shrink=500, the baseline direction); extending further only moves it closer to the baseline.',
 '- k has no effect for item CF because users have only ~13 rated movies in train_core, so there are never more than k neighbours.',
 '- Not tried (and why): SVD++/NMF and a TensorFlow model are optional in the brief; with ~3,200 training ratings a neural model is unlikely to beat these baselines.',
 '', '## Deployed recommender', f"- models/final_recommender.joblib = ItemCF{P['item_cf']} blended with popularity (alpha={ALPHA['item_cf']}), refit on train_full, with a popularity fallback for unknown users.",
 '- Other tuned models are saved in models/ for the Stage 10 comparison.']
Path('docs/model_selection.md').write_text('\n'.join(L)); print('\n'.join(L))
pd.set_option('display.width', 250)
print(); print(df[['exp_id', 'model', 'RMSE', 'MAE', 'P@10', 'R@10', 'Coverage@10']].round(3).to_string(index=False))
print('SVD seeds RMSE:', np.round(seeds, 4), 'mean', round(np.mean(seeds), 4), 'sd', round(np.std(seeds), 4))
