"""Stage 4 - profile data/raw/dataset_extended.csv; write docs/data_profile.md and data/processed/data_dictionary.csv"""
import numpy as np
import pandas as pd
from pathlib import Path

df = pd.read_csv('data/raw/dataset_extended.csv')
cat = pd.read_csv('data/raw/movie_catalogue.csv')
ts = pd.to_datetime(df.timestamp)
L = []
def add(s=''): L.append(s)

def gini(x):
    x = np.sort(np.asarray(x, float)); n = len(x)
    return (2 * np.arange(1, n + 1) - n - 1).dot(x) / (n * x.sum())

add('# Data Profile (auto-generated by src/profile_data.py)')
add(); add('## Structure'); add(f'- Shape: {df.shape[0]} rows x {df.shape[1]} columns'); add('- Dtypes: ' + str(df.dtypes.astype(str).to_dict()))
add('- Missing values per column: ' + str(df.isna().sum().to_dict()))
add(f'- Duplicate rows: {df.duplicated().sum()} | duplicate (user, movie) pairs: {df.duplicated(["user_id","movie_id"]).sum()}')
add(); add('## Domain / impossible-value checks')
add(f'- Ratings outside 1-5: {(~df.rating.between(1,5)).sum()} | not multiple of 0.5: {((df.rating*2)%1!=0).sum()}')
add(f'- release_year range: {df.release_year.min()}-{df.release_year.max()} | rated before release year: {(ts.dt.year < df.release_year).sum()}')
add(f'- Timestamp range: {ts.min()} to {ts.max()}')
add(f'- Whitespace/case problems in text columns: {sum((df[c] != df[c].str.strip()).sum() for c in ["movie_title","genre","language"])}')
add(f'- movie_id <-> movie_title is one-to-one: {df.groupby("movie_id").movie_title.nunique().eq(1).all() and df.groupby("movie_title").movie_id.nunique().eq(1).all()}')
add(); add('## Key measure: rating')
vc = df.rating.value_counts().sort_index()
add(f'- mean {df.rating.mean():.2f}, median {df.rating.median():.1f}, std {df.rating.std():.2f}, skew {df.rating.skew():.2f}')
add('- counts: ' + str(vc.to_dict()))
add(f'- Share rating >= 4.0 (planned relevance threshold for precision@K): {(df.rating>=4).mean():.1%}')
add(f'- Share rating >= 4.5: {(df.rating>=4.5).mean():.1%}')
add(); add('## Users and items')
pu = df.groupby('user_id').size(); pi = df.groupby('movie_id').size()
um = df.groupby('user_id').rating.mean(); us = df.groupby('user_id').rating.std()
im = df.groupby('movie_id').rating.mean()
add(f'- Users {len(pu)}; ratings/user min {pu.min()}, median {pu.median():.0f}, max {pu.max()}')
add(f'- Items {len(pi)}; ratings/item min {pi.min()}, median {pi.median():.0f}, max {pi.max()}')
add(f'- Density {len(df)/(len(pu)*len(pi)):.1%}; sparsity {1-len(df)/(len(pu)*len(pi)):.1%}')
add(f'- User mean rating: min {um.min():.2f}, max {um.max():.2f}, std {um.std():.2f} (rating-scale bias between users)')
add(f'- Users who gave the same rating to everything: {(us.fillna(0)==0).sum()}')
add(f'- Item mean rating: min {im.min():.2f}, max {im.max():.2f}, std {im.std():.2f}')
top10 = pi.sort_values(ascending=False).head(max(1, round(len(pi)*.1))).sum() / pi.sum()
add(f'- Popularity concentration: top 10% of movies receive {top10:.1%} of ratings; Gini of item popularity {gini(pi):.2f}')
add(f'- Movies with fewer than 20 ratings: {(pi<20).sum()} of {len(pi)}')
add(); add('## Catalogue composition')
add('- Languages: ' + str(cat.language.value_counts().to_dict()))
add('- Genres: ' + str(cat.genre.value_counts().to_dict()))
add(f'- Release years {cat.release_year.min()}-{cat.release_year.max()}; films from 2015 onward: {(cat.release_year>=2015).sum()}')
add(); add('## Provenance')
add(f'- is_original=True rows: {df.is_original.sum()} ({df.is_original.mean():.1%}); generated: {(~df.is_original).sum()}')
o = df[df.is_original]; g = df[~df.is_original]
add(f'- Mean rating original {o.rating.mean():.2f} vs generated {g.rating.mean():.2f}; users with originals: {o.user_id.nunique()}')
add(); add('## Main quality problems / risks')
add('- Mean rating is high and negatively skewed (users rate films they chose to watch).')
add('- Long-tail popularity: a few films dominate; cold-start items appear in a chronological split.')
add('- Original (is_original) rows carry no taste signal; synthetic rows are model-generated, not real behaviour.')
add('- No demographic columns exist, so demographic fairness cannot be measured (only activity and taste groups).')
Path('docs/data_profile.md').write_text('\n'.join(L)); print('\n'.join(L))

# ---------- data dictionary (descriptions written by hand, the rest computed) ----------
D = {
 'user_id':      ('integer', 'id', 'Positive integer (subset of 1-500)', 'Pseudonymous identifier of the viewer. A code, not a real person; no PII.', 'Key (with movie_id). Used by the model.'),
 'movie_title':  ('string', '-', '126 unique titles', 'Name of the film. One-to-one with movie_id.', 'Display only; the model uses movie_id.'),
 'genre':        ('categorical', '-', 'Action, Comedy, Drama, Romance, Sci-Fi, Thriller', 'Primary genre of the film (single label per film, simplification).', 'Fixed per movie. Used for diversity metrics and cold-start fallback, not for the CF models.'),
 'language':     ('categorical', '-', 'Hindi, Tamil, Telugu, Kannada, Malayalam, English', 'Original language of the film (English = Hollywood).', 'Fixed per movie. Used for regional-share and diversity metrics.'),
 'release_year': ('integer', 'year', '1975-2024', 'Year the film was released.', 'Fixed per movie. Used for novelty analysis; a rating is never earlier than this year.'),
 'rating':       ('float', 'stars', '1.0 to 5.0 in steps of 0.5', 'Score the user gave the film (1 = dislike, 5 = love). This is the TARGET of rating prediction.', 'Relevance for ranking metrics: rating >= 4.0. Never use as an input feature.'),
 'timestamp':    ('datetime (string)', 'YYYY-MM-DD HH:MM:SS', '2024-01-01 to 2025-12-31', 'Date and time the rating was given.', 'Used ONLY to order ratings for the chronological train/test split. Parsed to datetime in Stage 5.'),
 'movie_id':     ('string', 'id', 'M001-M126', 'Unique film code from movie_catalogue.csv.', 'Added in Stage 3. Key (with user_id). Used by the model.'),
 'is_original':  ('boolean', '-', 'True / False', 'True if the row comes from the provided dataset.csv; False if synthetically generated.', 'DO NOT USE as a model input: generation artefact (leakage of provenance). Only for audit.'),
}
rows = []
for c in df.columns:
    t, u, allowed, desc, note = D[c]
    s = df[c].head(3).astype(str).tolist()
    rows.append([c, t, u, allowed, *s, 'No' if df[c].notna().all() else 'Yes', desc, note])
dd = pd.DataFrame(rows, columns=['column_name','data_type','unit','allowed_values','sample_value_1','sample_value_2','sample_value_3','nullable','description','notes'])
Path('data/processed').mkdir(exist_ok=True)
dd.to_csv('data/processed/data_dictionary.csv', index=False)
print(); print(dd[['column_name','data_type','nullable']].to_string(index=False))
