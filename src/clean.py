"""Stage 5 - repeatable cleaning. Run from repo root:  python src/clean.py
Reads  data/raw/dataset_extended.csv (+ movie_catalogue.csv as source of truth for film attributes)
Writes data/processed/dataset.csv and docs/cleaning_log.md"""
import numpy as np
import pandas as pd
from pathlib import Path

GENRES = {'action': 'Action', 'comedy': 'Comedy', 'drama': 'Drama', 'romance': 'Romance', 'sci-fi': 'Sci-Fi', 'thriller': 'Thriller'}
LANGS = {l.lower(): l for l in ['Hindi', 'Tamil', 'Telugu', 'Kannada', 'Malayalam', 'English']}
COLS = ['user_id', 'movie_title', 'genre', 'language', 'release_year', 'rating', 'timestamp', 'movie_id', 'is_original']


def clean_ratings(df, catalogue):
    """Return (clean_df, log). Every step records rows before/after and the reason."""
    log = []
    def step(name, before, after, why):
        log.append((name, before, after, why))

    df = df.copy()
    n = len(df)
    # 1. types and text standardisation (no rows removed)
    for c in ['movie_title', 'genre', 'language', 'movie_id']:
        df[c] = df[c].astype('string').str.strip()
    df['genre'] = df.genre.str.lower().map(GENRES).astype('string').fillna(pd.NA)
    df['language'] = df.language.str.lower().map(LANGS).astype('string').fillna(pd.NA)
    df['rating'] = pd.to_numeric(df.rating, errors='coerce')
    df['user_id'] = pd.to_numeric(df.user_id, errors='coerce')
    df['release_year'] = pd.to_numeric(df.release_year, errors='coerce')
    df['timestamp'] = pd.to_datetime(df.timestamp, errors='coerce')
    step('Standardise text, coerce numeric/datetime types', n, len(df), 'Trim spaces, canonical genre/language spelling; unparseable values become missing')

    # 2. missing values: ratings cannot be imputed in collaborative filtering (it would invent preferences)
    b = len(df)
    df = df.dropna(subset=['user_id', 'movie_id', 'rating', 'timestamp', 'genre', 'language', 'release_year', 'movie_title'])
    step('Drop rows with missing/unparseable key fields', b, len(df), 'Rating/user/movie/time must not be imputed')
    df['user_id'] = df.user_id.astype(int); df['release_year'] = df.release_year.astype(int)

    # 3. impossible values (domain rules)
    b = len(df)
    df = df[df.rating.between(1, 5) & ((df.rating * 2) % 1 == 0)]
    step('Drop ratings outside 1-5 or not in 0.5 steps', b, len(df), 'Valid scale of the rating system')

    # 4. film attributes: the catalogue is the single source of truth
    b = len(df)
    cat = catalogue[['movie_id', 'movie_title', 'genre', 'language', 'release_year']]
    df = df.drop(columns=['movie_title', 'genre', 'language', 'release_year']).merge(cat, on='movie_id', how='inner', validate='m:1')
    step('Attach film attributes from catalogue; drop unknown movie_id', b, len(df), 'One fixed genre/language/year per film')

    # 5. no rating before the film existed
    b = len(df)
    df = df[df.timestamp.dt.year >= df.release_year]
    step('Drop ratings dated before the film release year', b, len(df), 'Anachronistic ratings are impossible')

    # 6. duplicates: one rating per (user, movie); keep the most recent
    b = len(df)
    df = df.sort_values('timestamp', kind='stable').drop_duplicates(['user_id', 'movie_id'], keep='last')
    step('Drop duplicate (user, movie) pairs (keep latest)', b, len(df), 'Matrix has one cell per user-movie pair')

    # 7. outliers: ratings are bounded, so none are removed; just record the check
    step('Outlier check (users/movies with extreme counts)', len(df), len(df), 'Bounded scale and 15-25 ratings/user: valid extremes kept')

    df = df.sort_values(['timestamp', 'user_id', 'movie_id'], kind='stable').reset_index(drop=True)
    df['timestamp'] = df.timestamp.dt.strftime('%Y-%m-%d %H:%M:%S')
    df['is_original'] = df.is_original.astype(bool) if 'is_original' in df else False
    return df[COLS], log


def main():
    raw = pd.read_csv('data/raw/dataset_extended.csv')
    cat = pd.read_csv('data/raw/movie_catalogue.csv')
    out, log = clean_ratings(raw, cat)
    Path('data/processed').mkdir(parents=True, exist_ok=True)
    out.to_csv('data/processed/dataset.csv', index=False)
    L = ['# Cleaning Log (auto-generated by src/clean.py)', '', f'Input: data/raw/dataset_extended.csv ({len(raw)} rows) -> Output: data/processed/dataset.csv ({len(out)} rows)', '',
         '| Step | Rows before | Rows after | Removed | Reason |', '|---|---|---|---|---|']
    L += [f'| {s} | {b} | {a} | {b-a} | {w} |' for s, b, a, w in log]
    L += ['', '## Decisions', '- No imputation: a missing rating cannot be estimated without inventing preferences.',
          '- is_original is kept in dataset.csv for traceability but is excluded from every model input.',
          '- timestamp stays a string in the CSV (YYYY-MM-DD HH:MM:SS); load with pd.to_datetime.',
          '- Cleaning removed no rows on this dataset because the generator already enforced the rules; the tests in tests/test_clean.py prove each rule works on dirty data.']
    Path('docs/cleaning_log.md').write_text('\n'.join(L)); print('\n'.join(L))


if __name__ == '__main__':
    main()
